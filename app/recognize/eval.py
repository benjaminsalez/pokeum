"""Offline accuracy evaluation over a folder of labelled card images.

Each image is named ``{card_id}__{anything}.jpg`` (the true card id before the
double underscore). This is the acceptance instrument for the recognition
milestones: it reports both *whether* the recognizer is right (top-1/top-k
accuracy) and *how safely* it is right (verdict counts, mean confidence, mean
margin over the runner-up), so a change's effect on real photos is measurable
rather than guessed.

Labelled test sets live under ``data/eval/`` by convention (gitignored):
``data/eval/synthetic`` (generated by ``scripts/make_synthetic_eval.py``) and
``data/eval/real`` (real-world listing photos).
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from app.models import RecognitionResult
from app.recognize.factory import build_recognizer
from app.vision.imaging import load_image

logger = logging.getLogger(__name__)

_IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}


def truth_from_name(path: Path) -> str | None:
    """Extract the labelled card id from a ``{card_id}__*`` filename."""
    stem = path.stem
    if "__" not in stem:
        return None
    return stem.split("__", 1)[0]


def evaluate_folder(
    folder: str | Path, *, data_dir: str | None = None, top_k: int = 5
) -> dict[str, Any]:
    """Recognize every labelled image in a folder and report the full scorecard.

    Args:
        folder: Directory of ``{card_id}__*`` labelled images.
        data_dir: Reference data root; defaults to the configured directory.
        top_k: Rank considered for top-k accuracy.

    Returns:
        A report dict: accuracy (top-1/top-k), verdict counts (confident /
        uncertain / no_match / no_card), mean confidence and mean margin of the
        winning card over its runner-up, and the list of misses.
    """
    root = Path(folder)
    images = sorted(
        p for p in root.iterdir() if p.is_file() and p.suffix.lower() in _IMAGE_SUFFIXES
    )
    recognizer = build_recognizer(data_dir=data_dir)

    total = 0
    top1 = 0
    topk = 0
    confidences: list[float] = []
    margins: list[float] = []
    statuses: dict[str, int] = {}
    misses: list[dict[str, str]] = []
    for path in images:
        truth = truth_from_name(path)
        if truth is None:
            logger.warning("skipping unlabelled file: %s", path.name)
            continue
        total += 1
        result = recognizer.identify(load_image(path), top_k=top_k)
        statuses[result.status.value] = statuses.get(result.status.value, 0) + 1
        ranked = _ranked_ids(result)
        if result.match is not None:
            confidences.append(result.match.confidence)
            runner_up = result.alternates[0].confidence if result.alternates else 0.0
            margins.append(result.match.confidence - runner_up)
        if ranked[:1] == [truth]:
            top1 += 1
        if truth in ranked:
            topk += 1
        else:
            misses.append({"file": path.name, "truth": truth, "got": ranked[0] if ranked else ""})

    return {
        "count": total,
        "top1": top1,
        "topk": topk,
        "top1_accuracy": round(top1 / total, 3) if total else 0.0,
        "topk_accuracy": round(topk / total, 3) if total else 0.0,
        "top_k": top_k,
        "verdicts": statuses,
        "mean_confidence": round(sum(confidences) / len(confidences), 3) if confidences else 0.0,
        "mean_margin": round(sum(margins) / len(margins), 3) if margins else 0.0,
        "misses": misses,
    }


def _ranked_ids(result: RecognitionResult) -> list[str]:
    """Return the recognized card ids, best first, from a result."""
    ids: list[str] = []
    if result.match is not None:
        ids.append(result.match.card.card_id)
    ids.extend(alt.card.card_id for alt in result.alternates)
    return ids
